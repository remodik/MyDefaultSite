export function getLang() {
    try {
        const stored = localStorage.getItem(STORAGE_KEY);
        if (stored && DICT[stored]) return stored;
    } catch {}
    const nav = typeof navigator !== 'undefined' ? (navigator.language || 'ru') : 'ru';
    const browser = String(nav).split('-')[0];
    if (DICT[browser]) return browser;
    return 'ru';
}

export function setLang(lang) {
    if (!DICT[lang]) return;
    try { localStorage.setItem(STORAGE_KEY, lang); } catch {}
    if (typeof document !== 'undefined') {
        document.documentElement.lang = lang;
    }
    applyDom();
    window.dispatchEvent(new CustomEvent('lang-changed', { detail: { lang } }));
}

export function t(key) {
    const lang = getLang();
    const dict = DICT[lang] || DICT.ru;
    return dict[key] ?? DICT.ru[key] ?? key;
}

// t() с подстановкой плейсхолдеров вида {name}, {n}.
export function tf(key, vars) {
    let out = t(key);
    for (const [name, value] of Object.entries(vars || {})) {
        out = out.split(`{${name}}`).join(String(value));
    }
    return out;
}

export function applyDom(root) {
    const scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (key) el.textContent = t(key);
    });
    scope.querySelectorAll('[data-i18n-html]').forEach(el => {
        const key = el.getAttribute('data-i18n-html');
        if (key) el.innerHTML = t(key);
    });
    scope.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (key) el.setAttribute('placeholder', t(key));
    });
    scope.querySelectorAll('[data-i18n-title]').forEach(el => {
        const key = el.getAttribute('data-i18n-title');
        if (key) el.setAttribute('title', t(key));
    });
    scope.querySelectorAll('[data-i18n-aria-label]').forEach(el => {
        const key = el.getAttribute('data-i18n-aria-label');
        if (key) el.setAttribute('aria-label', t(key));
    });
    if (typeof document !== 'undefined') {
        document.documentElement.classList.add('i18n-ready');
    }
}
